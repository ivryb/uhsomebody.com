"""Prepares every image the site ships from the sources in art/, so the browser only draws.

Run from the repo root after changing anything in art/:  python3 tools/prepare-assets.py

Writes, into public/ (the site):
  assets/room.webp           the studio picture
  assets/room-masks.png      each screen's shape as an alpha mask, stacked top to bottom
  scripts/room-data.js       where the screens and the city lights are in the picture
  assets/grain.png           the film-grain tile laid over the picture
  assets/listenly.webp, assets/findphotosofme.webp   project pictures, cropped to the card's shape
  favicon.svg, favicon.ico, favicon-96x96.png, apple-touch-icon.png, web-app-manifest-*.png
The OG image (og.jpg) is a screenshot of og.html; see that file.
"""
import json
import random

from PIL import Image, ImageDraw, ImageFilter

ROOM = Image.open("art/room.png").convert("RGB")
W, H = ROOM.size
# Lit windows only blink above this line; yellow below it is the cymbals.
SKYLINE = 0.47


def is_screen(r, g, b):
    return abs(r - 200) < 40 and abs(g - 168) < 40 and abs(b - 240) < 35


def is_light(r, g, b):
    return r > 190 and g > 150 and b < 140


def areas(test, max_y=H):
    """Connected areas of pixels that pass test, as (pixels, x0, y0, x1, y1)."""
    px = ROOM.load()
    seen = bytearray(W * H)
    found = []
    for start in range(W * max_y):
        if seen[start] or not test(*px[start % W, start // W]):
            continue
        seen[start] = 1
        stack, pixels = [start], []
        while stack:
            i = stack.pop()
            pixels.append(i)
            x, y = i % W, i // W
            for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
                n = ny * W + nx
                if 0 <= nx < W and 0 <= ny < max_y and not seen[n] and test(*px[nx, ny]):
                    seen[n] = 1
                    stack.append(n)
        xs = [i % W for i in pixels]
        ys = [i // W for i in pixels]
        found.append((pixels, min(xs), min(ys), max(xs), max(ys)))
    return found


# A screen's mask is grown by 2px and softened, so it swallows the anti-aliased lilac fringe around the
# screen and ends in a smooth edge. Content is warped onto the screen's corners: its pixels furthest
# along each diagonal.
PAD = 3


def screen(area, mask_y):
    pixels, x0, y0, x1, y1 = area
    w, h = x1 - x0 + 1 + PAD * 2, y1 - y0 + 1 + PAD * 2
    mask = Image.new("L", (w, h), 0)
    mp = mask.load()
    for i in pixels:
        mp[i % W - x0 + PAD, i // W - y0 + PAD] = 255
    mask = mask.filter(ImageFilter.MaxFilter(5)).filter(ImageFilter.GaussianBlur(0.7))
    corner = lambda score: max(pixels, key=lambda i: score(i % W, i // W))
    quad = [corner(lambda x, y: -x - y), corner(lambda x, y: x - y), corner(lambda x, y: x + y), corner(lambda x, y: y - x)]
    quad = [[i % W - x0 + PAD, i // W - y0 + PAD] for i in quad]
    return mask, {"x": x0 - PAD, "y": y0 - PAD, "w": w, "h": h, "maskY": mask_y, "quad": quad}


def room():
    ROOM.save("public/assets/room.webp", quality=88, method=6)
    found = sorted((a for a in areas(is_screen) if len(a[0]) > 3000), key=lambda a: -len(a[0]))
    # The three monitors left to right, then the laptop; room.js gives them their apps in this order.
    found = sorted(found[:3], key=lambda a: a[1]) + found[3:]
    masks, screens, y = [], [], 0
    for a in found:
        mask, data = screen(a, y)
        masks.append(mask)
        screens.append(data)
        y += mask.height
    sheet = Image.new("LA", (max(m.width for m in masks), y), (0, 0))
    y = 0
    for m in masks:
        sheet.paste(Image.merge("LA", (Image.new("L", m.size, 255), m)), (0, y))
        y += m.height
    sheet.save("public/assets/room-masks.png", optimize=True)
    lights = [[x0 - 1, y0 - 1, x1 - x0 + 3, y1 - y0 + 3] for p, x0, y0, x1, y1 in areas(is_light, round(H * SKYLINE)) if len(p) > 6]
    data = {"width": W, "height": H, "screens": screens, "lights": lights}
    with open("public/scripts/room-data.js", "w") as f:
        f.write("// Generated by tools/prepare-assets.py from art/room.png; don't edit by hand.\n")
        f.write(f"export default {json.dumps(data, separators=(',', ':'))};\n")


def grain():
    """Sparse white specks, drawn at 2x and shown at half size, so each is one device pixel on retina screens."""
    random.seed(7)
    tile = Image.new("LA", (256, 256), (255, 0))
    px = tile.load()
    for y in range(256):
        for x in range(256):
            a = 4 * random.gauss(0.5, 0.11) - 2.3
            if a > 0:
                # Four alpha levels look the same as 256 and compress several times smaller.
                px[x, y] = (255, min(255, 64 * (1 + min(3, int(a * 4)))))
    tile.save("public/assets/grain.png", optimize=True)


def projects():
    # Both cards show their picture at 1200:630; the Listenly screenshot keeps its top, the headline.
    home = Image.open("art/listenly-home.png").convert("RGB")
    home = home.crop((0, 0, home.width, round(home.width * 630 / 1200))).resize((1280, 672), Image.LANCZOS)
    home.save("public/assets/listenly.webp", quality=82, method=6)
    Image.open("art/findphotosofme-og.png").convert("RGB").save("public/assets/findphotosofme.webp", quality=82, method=6)


def favicons():
    """A fuchsia block cursor on a black tile. Every size is drawn natively so 16px stays pixel-sharp."""
    def icon(size, rounded=True):
        s = size / 16
        im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        d.rounded_rectangle([0, 0, size - 1, size - 1], radius=round(2 * s) if rounded else 0, fill=(0, 0, 0, 255))
        d.rectangle([round(5 * s), round(3 * s), round(11 * s) - 1, round(13 * s) - 1], fill=(0xED, 0x6A, 0xFF, 255))
        return im

    with open("public/favicon.svg", "w") as f:
        f.write('<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" shape-rendering="crispEdges">'
                '<rect width="16" height="16" rx="2" fill="#000"/><rect x="5" y="3" width="6" height="10" fill="#ed6aff"/></svg>\n')
    icon(48).save("public/favicon.ico", sizes=[(16, 16), (32, 32), (48, 48)], append_images=[icon(16), icon(32)])
    icon(96).save("public/favicon-96x96.png", optimize=True)
    # iOS and Android round or mask the corners themselves, so these are opaque squares.
    icon(180, rounded=False).save("public/apple-touch-icon.png", optimize=True)
    icon(192, rounded=False).save("public/web-app-manifest-192x192.png", optimize=True)
    icon(512, rounded=False).save("public/web-app-manifest-512x512.png", optimize=True)


room()
grain()
projects()
favicons()
